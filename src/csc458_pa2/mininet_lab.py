from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
import time
from typing import Any

from .addressing import (
    endpoint_ip, host_ip, host_name, intf_name, node_name,
    router_stub_ip, stub_intf_name, stub_prefix,
)
from .oracle import expected_prefix_routes
from .topology import Topology


def require_mininet():
    try:
        from mininet.cli import CLI
        from mininet.link import TCLink
        from mininet.net import Mininet
        from mininet.node import Node
    except ImportError as e:
        raise RuntimeError(
            "Mininet is not installed for this Python interpreter. Run tools/check_environment.py "
            "and use the course VM/native Ubuntu setup described in README.md."
        ) from e
    return CLI, TCLink, Mininet, Node


class MininetLab:
    def __init__(self, topology: Topology, workdir: str | Path, protocol: str, dv_mode: str = "poison_reverse", capture: bool = False):
        self.topology = topology
        self.workdir = Path(workdir).resolve()
        self.protocol = protocol.upper()
        self.dv_mode = dv_mode
        self.capture = capture
        self.net = None
        self.processes = []
        self.capture_processes = []
        self.started = False
        self.src_dir = Path(__file__).resolve().parents[1]
        self.current_costs = {k: v.cost for k, v in topology.links.items()}

    def build(self):
        CLI, TCLink, Mininet, Node = require_mininet()

        class LinuxRouter(Node):
            def config(self, **params):
                super().config(**params)
                self.cmd("sysctl -qw net.ipv4.ip_forward=1")
                self.cmd("sysctl -qw net.ipv4.conf.all.rp_filter=0")
                self.cmd("sysctl -qw net.ipv4.conf.default.rp_filter=0")
            def terminate(self):
                self.cmd("sysctl -qw net.ipv4.ip_forward=0")
                super().terminate()

        net = Mininet(controller=None, build=False, link=TCLink, autoSetMacs=True)
        routers = {}
        hosts = {}
        for rid in self.topology.routers:
            routers[rid] = net.addHost(node_name(rid), cls=LinuxRouter, ip=None)
            hosts[rid] = net.addHost(host_name(rid), ip=None)
            net.addLink(
                routers[rid], hosts[rid],
                intfName1=stub_intf_name(rid),
                intfName2=f"{host_name(rid)}-{node_name(rid)}",
            )
        for link in self.topology.links.values():
            net.addLink(
                routers[link.a], routers[link.b],
                intfName1=intf_name(link.a, link.b),
                intfName2=intf_name(link.b, link.a),
                delay=f"{link.delay_ms}ms", use_htb=True,
            )
        net.build()
        net.start()
        self.net = net

        for rid in self.topology.routers:
            r, h = routers[rid], hosts[rid]
            rif = stub_intf_name(rid)
            hif = f"{host_name(rid)}-{node_name(rid)}"
            r.cmd(f"ip addr flush dev {rif}")
            r.cmd(f"ip addr add {router_stub_ip(rid)}/24 dev {rif}")
            r.cmd(f"ip link set {rif} up")
            h.cmd(f"ip addr flush dev {hif}")
            h.cmd(f"ip addr add {host_ip(rid)}/24 dev {hif}")
            h.cmd(f"ip link set {hif} up")
            h.cmd("ip route del default 2>/dev/null || true")
            h.cmd(f"ip route add default via {router_stub_ip(rid)}")

        for link in self.topology.links.values():
            for local, peer in ((link.a, link.b), (link.b, link.a)):
                r = routers[local]
                iface = intf_name(local, peer)
                r.cmd(f"ip addr flush dev {iface}")
                r.cmd(f"ip addr add {endpoint_ip(link.a, link.b, local)}/30 dev {iface}")
                r.cmd(f"ip link set {iface} up")
            if not link.active:
                net.configLinkStatus(node_name(link.a), node_name(link.b), "down")

        # Disable reverse-path filtering on every router interface.
        # This is necessary because ICMP Time Exceeded messages generated by
        # intermediate routers may use transit-link addresses that are not
        # advertised by the student DV/LS protocol.
        for rid in self.topology.routers:
            r = routers[rid]

            r.cmd("sysctl -qw net.ipv4.conf.all.rp_filter=0")
            r.cmd("sysctl -qw net.ipv4.conf.default.rp_filter=0")

            for intf in r.intfList():
                if intf.name != "lo":
                    r.cmd(
                        f"sysctl -qw net.ipv4.conf.{intf.name}.rp_filter=0"
                    )
        self._prepare_run_files()
        return self

    def _router_config(self, rid: str) -> dict[str, Any]:
        neighbors = {}
        for link in self.topology.links.values():
            if rid not in (link.a, link.b):
                continue
            peer = link.other(rid)
            neighbors[peer] = {
                "cost": self.current_costs[link.key()],
                "ifname": intf_name(rid, peer),
                "local_ip": endpoint_ip(link.a, link.b, rid),
                "peer_ip": endpoint_ip(link.a, link.b, peer),
                "active": bool(link.active),
            }
        return {"router_id": rid, "own_prefix": stub_prefix(rid), "neighbors": neighbors}

    def _prepare_run_files(self) -> None:
        self.workdir.mkdir(parents=True, exist_ok=True)
        for d in ("config", "status", "commands", "logs", "captures"):
            (self.workdir / d).mkdir(exist_ok=True)
        for rid in self.topology.routers:
            (self.workdir / "config" / f"{rid}.json").write_text(json.dumps(self._router_config(rid), indent=2, sort_keys=True))
            (self.workdir / "commands" / f"{rid}.jsonl").write_text("")

    def start_daemons(self) -> None:
        if self.net is None:
            raise RuntimeError("build() first")
        env = os.environ.copy()
        env["PYTHONPATH"] = str(self.src_dir) + os.pathsep + env.get("PYTHONPATH", "")
        for rid in self.topology.routers:
            node = self.net[node_name(rid)]
            cmd = [
                sys.executable, "-m", "csc458_pa2.daemon",
                "--config", str(self.workdir / "config" / f"{rid}.json"),
                "--protocol", self.protocol,
                "--dv-mode", self.dv_mode,
                "--status", str(self.workdir / "status" / f"{rid}.json"),
                "--commands", str(self.workdir / "commands" / f"{rid}.jsonl"),
                "--log", str(self.workdir / "logs" / f"{rid}.log"),
            ]
            self.processes.append(node.popen(cmd, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))
        if self.capture:
            self.start_capture()

    def start_capture(self) -> None:
        if self.net is None:
            return
        if subprocess.run(["sh", "-c", "command -v tcpdump >/dev/null"], check=False).returncode != 0:
            print("warning: tcpdump not installed; packet capture disabled", file=sys.stderr)
            return
        for rid in self.topology.routers:
            node = self.net[node_name(rid)]
            out = self.workdir / "captures" / f"{rid}.pcap"
            self.capture_processes.append(node.popen(["tcpdump", "-U", "-n", "-i", "any", "udp", "port", "4582", "-w", str(out)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL))

    def command(self, rid: str, obj: dict[str, Any]) -> None:
        path = self.workdir / "commands" / f"{rid}.jsonl"
        with path.open("a") as f:
            f.write(json.dumps(obj, sort_keys=True) + "\n")
            f.flush()

    def set_cost(self, a: str, b: str, cost: int) -> None:
        a, b = a.upper(), b.upper()
        if not 1 <= cost < 16:
            raise ValueError("cost must be in [1,15]")
        link = self.topology.link(a, b)
        link.cost = cost
        self.current_costs[link.key()] = cost
        self.command(a, {"type": "cost_change", "neighbor": b, "cost": cost})
        self.command(b, {"type": "cost_change", "neighbor": a, "cost": cost})

    def set_link(self, a: str, b: str, up: bool) -> None:
        if self.net is None:
            raise RuntimeError("network not running")
        a, b = a.upper(), b.upper()
        link = self.topology.link(a, b)
        link.active = up
        self.net.configLinkStatus(node_name(a), node_name(b), "up" if up else "down")

    def status(self, rid: str) -> dict | None:
        path = self.workdir / "status" / f"{rid.upper()}.json"
        if not path.exists():
            return None
        try:
            return json.loads(path.read_text())
        except (json.JSONDecodeError, OSError):
            return None

    def routes_match_oracle(self) -> bool:
        for rid in self.topology.routers:
            s = self.status(rid)
            if not s:
                return False
            actual = {p: (int(v["metric"]), v["next_hop"]) for p, v in s.get("routes", {}).items()}
            expected = {p: (r.metric, r.next_hop) for p, r in expected_prefix_routes(self.topology, rid).items()}
            if actual != expected:
                return False
        return True

    def wait_for_convergence(self, timeout: float | None = None, stable_for: float = 0.6) -> float | None:
        timeout = self.topology.convergence_timeout if timeout is None else timeout
        start = time.monotonic()
        stable_start = None
        while time.monotonic() - start < timeout:
            if self.routes_match_oracle():
                if stable_start is None:
                    stable_start = time.monotonic()
                if time.monotonic() - stable_start >= stable_for:
                    return time.monotonic() - start
            else:
                stable_start = None
            time.sleep(0.1)
        return None

    def ping(self, src_router: str, dst_router: str, count: int = 2) -> str:
        if self.net is None:
            raise RuntimeError("network not running")
        src = self.net[host_name(src_router.upper())]
        return src.cmd(f"ping -c {count} -W 1 {host_ip(dst_router.upper())}")

    def traceroute(self, src_router: str, dst_router: str) -> str:
        if self.net is None:
            raise RuntimeError("network not running")
        src = self.net[host_name(src_router.upper())]
        return src.cmd(f"traceroute -n -w 1 -q 1 {host_ip(dst_router.upper())}")

    def aggregate_stats(self) -> dict[str, int]:
        total = {"messages_sent": 0, "bytes_sent": 0, "messages_received": 0, "bytes_received": 0}
        for rid in self.topology.routers:
            s = self.status(rid) or {}
            for k in total:
                total[k] += int(s.get("stats", {}).get(k, 0))
        return total

    def stop(self) -> None:
        for rid in self.topology.routers:
            try:
                self.command(rid, {"type": "stop"})
            except OSError:
                pass
        time.sleep(0.2)
        for p in self.capture_processes + self.processes:
            try:
                p.terminate()
            except Exception:
                pass
        for p in self.capture_processes + self.processes:
            try:
                p.wait(timeout=1)
            except Exception:
                try:
                    p.kill()
                except Exception:
                    pass
        if self.net is not None:
            self.net.stop()
            self.net = None

    def __enter__(self):
        return self.build()

    def __exit__(self, exc_type, exc, tb):
        self.stop()
